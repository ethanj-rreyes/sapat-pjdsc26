"""Export province and selected-city PSA prices for the web apps into web/shared/data/local_prices.js (global SAPAT_LOCAL).

Regional prices (sapat_data.js) stay the base; the apps use these finer prices only for the foods a province or city prices.
Prices are PHP per kg as purchased; per-piece items (eggs, coconut) are converted with the grams per piece in sapat/foods.py.
Each value is the mean of PSA's rows for that place, food and month, rounded to centavos.

Usage: python scripts/export_local_prices.py [--since 2024-01]
Input: data_clean/psa_prices_long_province.csv.gz (from scripts/build_clean_data.py)
       web/shared/data/places.js (only to link each PSA place name to its region and key)
"""
import argparse
import json
import os
import re
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from sapat.foods import EXCLUDED, FOODS  # noqa: E402

DATA = os.path.join(ROOT, "data_clean")
OUT = os.path.join(ROOT, "web", "shared", "data", "local_prices.js")
PLACES = os.path.join(ROOT, "web", "shared", "data", "places.js")


def load_js_global(path, name):
    txt = open(path, encoding="utf-8").read()
    start = txt.index(f"window.{name} =") + len(f"window.{name} =")
    return json.loads(txt[start:].strip().rstrip(";"))


def psa_places():
    """PSA series key -> (region, display name), read from the places tree."""
    out = {}
    for region, r in load_js_global(PLACES, "SAPAT_PLACES").items():
        for p in r.get("provinces", []):
            if p.get("psa"):
                out[p["psa"]] = region
            for c in p.get("cities", []):
                if c.get("psa"):
                    out[c["psa"]] = region
        for c in r.get("cities", []):
            if c.get("psa"):
                out[c["psa"]] = region
    return out


def slug(name):
    """PSA place name -> key used in places.js, e.g. 'City of Lapu-lapu' -> 'city-of-lapu-lapu'."""
    return re.sub(r"\s+", "-", name.strip().lower())


def main(since):
    d = pd.read_csv(os.path.join(DATA, "psa_prices_long_province.csv.gz"), parse_dates=["date"])
    d = d[(d.date >= since) & d.psa_commodity.isin(FOODS) & ~d.psa_commodity.isin(EXCLUDED)].copy()
    d["food"] = d.psa_commodity.map(lambda c: FOODS[c][0])
    d["php_per_kg"] = d.price * 1000 / d.psa_commodity.map(lambda c: FOODS[c][5])
    mean = d.groupby(["geo_name", "date", "food"]).php_per_kg.mean().round(2)

    region_of = psa_places()
    by_slug = {k.split(":", 1)[1]: k for k in region_of}
    provinces, unmatched = [], []
    for name, g in mean.groupby(level=0):
        key = by_slug.get(slug(name))
        if key is None:
            unmatched.append(name)
            continue
        prices = {}
        for (_, date, food), v in g.items():
            prices.setdefault(date.strftime("%Y-%m"), {})[food] = float(v)
        provinces.append(dict(key=key, name=name, region=key.split(":")[0], prices=prices))
    provinces.sort(key=lambda p: p["key"])
    months = sorted({m for p in provinces for m in p["prices"]})
    out = dict(generated=pd.Timestamp.now().strftime("%Y-%m-%d"),
               source=f"PSA OpenSTAT Retail Price Survey, provinces and selected cities ({months[0]} to {months[-1]})",
               provinces=provinces, markets=[])
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by scripts/export_local_prices.py from data_clean/psa_prices_long_province.csv.gz.\n"
                 " * provinces: [{ key, name, region, prices: { 'YYYY-MM': { foodKey: PHP per kg } } }]\n"
                 " * markets: per-market readings (none yet; see docs/LIMITATIONS.md). */\n")
        fh.write("window.SAPAT_LOCAL = ")
        json.dump(out, fh, separators=(",", ":"))
        fh.write(";\n")
    print(f"wrote {OUT}: {len(provinces)} places, {len(months)} months" + (f"; unmatched: {unmatched}" if unmatched else ""))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--since", default="2024-01", help="first month to export (YYYY-MM)")
    main(ap.parse_args().since + "-01")
