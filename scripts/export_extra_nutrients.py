"""Export the extra nutrients the family app tracks (fat, carbohydrate, fiber, vitamin C) into
web/shared/data/extra_nutrients.js (global SAPAT_EXTRA).

Values are per gram AS PURCHASED: PhilFCT value per 100 g edible portion x edible share / 100 / 100,
the same conversion sapat/data.py uses for the five planning nutrients.

Usage: python scripts/export_extra_nutrients.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from sapat.data import load_panel  # noqa: E402

FIELDS = ["fat_g", "carb_g", "fiber_g", "vit_c_mg"]
OUT = os.path.join(ROOT, "web", "shared", "data", "extra_nutrients.js")


def main():
    p = load_panel().drop_duplicates("food_key").set_index("food_key")
    foods = {k: [round(float(r[f]) * float(r.ep_pct) / 100 / 100, 5) for f in FIELDS] for k, r in p.iterrows()}
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by scripts/export_extra_nutrients.py from data_clean/nutrient_price_panel.csv.gz.\n"
                 "   Per gram AS PURCHASED (PhilFCT per-100 g edible value x edible share / 100). Order: " + ", ".join(FIELDS) + " */\n")
        fh.write("window.SAPAT_EXTRA = ")
        json.dump(dict(fields=FIELDS, foods=foods), fh, separators=(",", ":"))
        fh.write(";\n")
    print(f"wrote {OUT}: {len(foods)} foods")


if __name__ == "__main__":
    main()
