"""Export the core data bundle for the web apps into web/shared/data/sapat_data.js (one global, SAPAT_DATA).

Run after scripts/compute_index.py:   python scripts/export_app_data.py
"""
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from sapat.data import DATA, ROOT, food_meta, price_cube  # noqa: E402
from sapat.foods import GROUP_LABELS  # noqa: E402
from sapat.typical import GROUPS, decile_budgets  # noqa: E402

SRC_CODE = {"": 0, "observed": 1, "recent": 2, "estimated": 3}


def main():
    meta = food_meta()
    est, src = price_cube()
    keys = list(meta.index)
    months = sorted(d.strftime("%Y-%m") for d in est.index.get_level_values(1).unique())
    rx = pd.read_csv(os.path.join(DATA, "region_crosswalk.csv"))
    region_names = dict(zip(rx.region_key, rx.region_short))
    region_names["PH"] = "Philippines (national average)"
    region_names["NIR"] = "Negros Island Region"

    prices, sources = {}, {}
    for r in ["PH"] + list(rx.region_key):
        P = est.loc[r].reindex(columns=keys) * 1000  # PHP per kg as purchased
        S = src.loc[r].reindex(columns=keys).fillna("")
        prices[r] = [None if not np.isfinite(v) else round(float(v), 2) for v in P.to_numpy().ravel()]
        sources[r] = [SRC_CODE[s] for s in S.to_numpy().ravel()]

    foods = []
    for k, f in meta.iterrows():
        foods.append(dict(key=k, name=f["name"], group=f.group, cap=float(f.cap), unit=f.unit, grams_per_unit=float(f.grams_per_unit),
                          ep_pct=float(f.ep_pct), fct_id=f.fct_id, energy_kcal=f.energy_kcal, protein_g=f.protein_g, iron_mg=f.iron_mg,
                          vit_a_ug=f.vit_a_ug, calcium_mg=f.calcium_mg))

    db = decile_budgets(2023)
    deciles = {}
    for r, d in db.groupby("region_key"):
        deciles[r] = {int(x.decile): dict(food_home_pc_day=round(x.food_home_pc_day, 2), **{g: round(x[f"share_{g}"], 4) for g in GROUPS})
                      for _, x in d.iterrows()}

    idx = pd.read_csv(os.path.join(ROOT, "outputs", "cond_index.csv"))
    index = {r: dict(months=list(d.month), cond=[round(v, 2) for v in d.cond_pp_day], cond_nocal=[round(v, 2) for v in d.cond_no_calcium_pp_day],
                     level=list(d.level), vs_prev3=[None if pd.isna(v) else round(v, 4) for v in d.vs_prev3],
                     yoy=[None if pd.isna(v) else round(v, 4) for v in d.yoy])
             for r, d in idx.groupby("region_key")}
    # Ratio to scale 2023 FIES budgets to a later month's prices: CoND(month) / mean CoND(2023)
    base23 = idx[idx.month.str.startswith("2023")].groupby("region_key").cond_pp_day.mean().round(3).to_dict()

    ry = pd.read_csv(os.path.join(DATA, "region_year_panel.csv"))
    ry = ry[ry.year == 2023].merge(pd.read_csv(os.path.join(DATA, "psa_thresholds_2018_2021_2023.csv"))[["region_key", "poverty_incidence_fam_pct_2023"]], on="region_key", how="left")
    stats = {r.region_key: dict(food_share_income=round(r.food_share_income_agg, 4), cereal_share=round(r.cereal_share_home_agg, 4),
                                animal_share=round(r.animal_src_share_home_agg, 4), below_ft=round(r.pct_pop_food_spend_below_ft, 4),
                                food_threshold_day=round(r.food_threshold_pc_yr / 365, 2), food_pc_day=round(r.food_pc_day_mean, 2),
                                poverty_fam=None if pd.isna(r.poverty_incidence_fam_pct_2023) else float(r.poverty_incidence_fam_pct_2023))
             for _, r in ry.iterrows()}

    out = dict(generated=pd.Timestamp.now().strftime("%Y-%m-%d"), months=months, foods=foods, group_labels=GROUP_LABELS,
               regions=[dict(key=k, name=region_names.get(k, k)) for k in ["PH"] + list(rx.region_key)],
               prices=prices, sources=sources, deciles=deciles, index=index, base2023=base23, stats=stats)
    path = os.path.join(ROOT, "web", "shared", "data", "sapat_data.js")
    with open(path, "w") as fh:
        fh.write("/* Generated by scripts/export_app_data.py from data_clean/ and outputs/cond_index.csv */\n")
        fh.write("window.SAPAT_DATA = ")
        json.dump(out, fh, separators=(",", ":"))
        fh.write(";\n")
    print("wrote", path, f"{os.path.getsize(path) / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
